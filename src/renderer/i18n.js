// The Vietnamese tables were written to one reader, "anh". Public text uses the address word she was given, default "bạn".
const NEUTRAL_EXEMPT = new Set(['lookTuning.rim']); // "anh sang": unaccented "ánh sáng", not a form of address
// Only the address word: "Anh" after "tiếng" (the English language) or "quốc" (Vương quốc Anh, the UK) is a proper name, never the
// reader (R8-F2: the vi language picker read "Tiếng Bạn"). check:public-text pins every rewritten string.
const ANH_WORD = /(?<![\p{L}\p{N}])(?<!(?:[Tt]iếng|quốc) )(a|A)nh(?![\p{L}\p{N}])/gu;
function neutralAddress(table) {
  const out = {};
  for (const [k, v] of Object.entries(table)) {
    if (NEUTRAL_EXEMPT.has(k) || typeof v !== 'string' || !ANH_WORD.test(v)) { ANH_WORD.lastIndex = 0; continue; }
    ANH_WORD.lastIndex = 0;
    out[k] = v.replace(ANH_WORD, (_, a) => (a === 'A' ? '{User}' : '{user}'));
  }
  return out;
}
