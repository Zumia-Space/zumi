// Name of the app the first-run import reads from, set once the sidecar has detected it ("Zumi 0.2.10"); until then neutral.
let importAppLabel = 'Zumi (desktop)';

// How Zumi says "I" and "you" in her Vietnamese lines ({self}/{user}, capitalised {Self}/{User}), from the host's soul. Until the
// host answers: the public default of soul-templates.json.
let address = { selfWord: 'em', userWord: 'bạn' };
const capFirst = (w) => w.charAt(0).toLocaleUpperCase('vi') + w.slice(1);
export function setImportAppLabel(label) { if (typeof label === 'string' && label) importAppLabel = label; }

function interpolate(s, vars) {
  if (!vars) vars = {};
  if (vars.app == null) vars = { ...vars, app: importAppLabel };
  vars = { self: address.selfWord, Self: capFirst(address.selfWord), user: address.userWord, User: capFirst(address.userWord), ...vars };
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}

// English string for a key, regardless of the active locale — used by modules that must expose a stable literal
// (e.g. a fallback shown before the locale is loaded, or a Node check that runs with no locale).
export function en(key) {
  return EN[key] != null ? EN[key] : key;
}

// Active-locale string; falls back to English, then to the key itself (so a missing key is visible, never blank).
export function t(key, vars) {
  const table = TABLES[current] || EN;
  const over = publicBuild ? PUBLIC_TABLES[current] : null;
  const raw = over && over[key] != null ? over[key] : table[key] != null ? table[key] : (EN[key] != null ? EN[key] : key);
  return interpolate(raw, vars);
}

export function getLocale() { return current; }

/** The UI language a first run (no uiLang saved) opens in, from the OS locale as the webview reports it (navigator.languages, most
 *  preferred first): vi* -> vi, zh* -> zh, anything else -> en (owner 0.3.0 review, option A). A saved uiLang always wins (the host). */
export function osUiLang(languages) {
  const first = String((Array.isArray(languages) ? languages[0] : languages) || '').toLowerCase();
  return first.startsWith('vi') ? 'vi' : first.startsWith('zh') ? 'zh' : 'en';
}

export function setLocale(lang) {
  const next = TABLES[lang] ? lang : DEFAULT_LOCALE;
  if (next === current) return current;
  current = next;
  for (const cb of listeners) { try { cb(current); } catch (e) { console.error(e); } }
  return current;
}

/** The host's soul (or anything with selfWord/userWord). A change repaints everything a locale change does; the app's listener reloads an open board only when the locale itself changed. */
export function setAddress(soul) {
  const selfWord = soul && soul.selfWord, userWord = soul && soul.userWord;
  if (typeof selfWord !== 'string' || typeof userWord !== 'string' || !selfWord || !userWord) return;
  if (selfWord === address.selfWord && userWord === address.userWord) return;
  address = { selfWord, userWord };
  for (const cb of listeners) { try { cb(current); } catch (e) { console.error(e); } }
}

export function onLocaleChange(cb) { listeners.add(cb); return () => listeners.delete(cb); }

// Repaint the static shell: every element carrying data-i18n(-html|-title|-aria|-placeholder) gets the active-locale
// text. Called once at boot and again on every locale change; the app's dynamic lines repaint via onLocaleChange.
export function apply(root) {
  const doc = root || document;
  for (const el of doc.querySelectorAll('[data-i18n]')) el.textContent = t(el.getAttribute('data-i18n'));
  for (const el of doc.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.getAttribute('data-i18n-html'));
  for (const el of doc.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  for (const el of doc.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  for (const el of doc.querySelectorAll('[data-i18n-placeholder]')) el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : current;
}
