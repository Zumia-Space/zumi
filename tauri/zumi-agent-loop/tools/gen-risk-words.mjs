// Regenerates src/risk_words.rs from the upstream word tables (read-only input, never run): node gen-risk-words.mjs <path to server/saved-steps/screen-words.ts>
import fs from 'node:fs';
const src = fs.readFileSync(process.argv[2], 'utf8');
function table(name) {
  const start = src.indexOf(`export const ${name}`);
  const open = src.indexOf('= {', start) + 2;
  const close = src.indexOf('\n};', open) + 2;
  const m = start < 0 ? null : [null, src.slice(open, close)];
  if (!m) throw new Error(`no ${name}`);
  return new Function(`return (${m[1]})`)();
}
const q = (s) => JSON.stringify(s);
let out = '// GENERATED by tools/gen-risk-words.mjs from upstream server/saved-steps/screen-words.ts (v0.1.169). Do not edit by hand.\n';
out += '/// (language, unspaced, words). A word: `=word` exact label, `word*` prefix, else whole word.\npub type Table = &\'static [(&\'static str, bool, &\'static [&\'static str])];\n\n';
for (const [rust, name] of [['FINAL_ACTIONS', 'FINAL_ACTIONS'], ['SECRET_FIELDS', 'SECRET_FIELDS']]) {
  const t = table(name);
  out += `pub const ${rust}: Table = &[\n`;
  for (const [lang, v] of Object.entries(t)) out += `    (${q(lang)}, ${!!v.unspaced}, &[${v.words.map(q).join(', ')}]),\n`;
  out += '];\n\n';
}
fs.writeFileSync(new URL('../src/risk_words.rs', import.meta.url), out);
console.log('ok');
